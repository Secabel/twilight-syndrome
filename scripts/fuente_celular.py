SPACE = 3      # ancho del espacio
GAP = 1        # espacio libre despues de la sombra
TOP = 7        # fila de la celda donde empieza un glifo de 9 filas

def width(text, gap=None):
    gap = GAP if gap is None else gap
    w = 0
    for i, ch in enumerate(text):
        if ch == ' ':
            w += SPACE
        else:
            rows, _ = G[ch]
            w += len(rows[0]) + 1 + (gap if i < len(text) - 1 else 0)
    return w

def render(text, cell_w=None, cell_h=16, x0=0, top=TOP, gap=None):
    """Devuelve matriz [fila][col] con indices 0/1/2."""
    gap = GAP if gap is None else gap
    w = width(text, gap) + x0
    W = max(cell_w or 0, w)
    m = [[0] * W for _ in range(cell_h)]
    x = x0
    for i, ch in enumerate(text):
        if ch == ' ':
            x += SPACE; continue
        rows, dt = G[ch]
        for yy, r in enumerate(rows):
            for xx, c in enumerate(r):
                if c == '#':
                    m[top + dt + yy][x + xx] = 1
        x += len(rows[0]) + 1 + gap
    # sombra: 1 px a la derecha de cada pixel de trazo, si esta libre
    for y in range(cell_h):
        for xx in range(W - 1, -1, -1):
            if m[y][xx] == 1 and xx + 1 < W and m[y][xx + 1] == 0:
                m[y][xx + 1] = 2
    return m
